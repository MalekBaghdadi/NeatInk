void main() {
  final lex = Lexicon.parse(
    File('assets/htr/word_freq.txt').readAsStringSync(),
    studyText: File('assets/htr/subject_words.txt').readAsStringSync(),
  );
  final p = TextPolisher(lex);

  ({int right, int wrong, int unmarked}) score(Map<String, String> set) {
    var right = 0, wrong = 0, unmarked = 0;
    set.forEach((bad, good) {
      final s = p.suggest('the $bad here').where((x) => x.original.toLowerCase() == bad).firstOrNull;
      if (s == null) {
        if (p.isKnownSpelling(bad)) unmarked++;
      } else if (s.replacement.toLowerCase() == good) {
        right++;
      } else {
        wrong++;
      }
    });
    return (right: right, wrong: wrong, unmarked: unmarked);
  }

  test('common misspellings are fixed', () {
    final g = score(general);
    expect(g.right, greaterThanOrEqualTo(120), reason: '$g of ${general.length}');
    expect(g.wrong + g.unmarked, lessThanOrEqualTo(3), reason: '$g');
  });

  test('misspelt terms of her courses are fixed', () {
    final s = score(subject);
    expect(s.right, greaterThanOrEqualTo(66), reason: '$s of ${subject.length}');
    expect(s.wrong + s.unmarked, lessThanOrEqualTo(1), reason: '$s');
  });

  test('misspellings the rules were not built from', () {
    final h = score(heldOut);
    expect(h.right, greaterThanOrEqualTo(85), reason: '$h of ${heldOut.length}');
    expect(h.wrong, lessThanOrEqualTo(5), reason: '$h');
    expect(h.unmarked, lessThanOrEqualTo(1), reason: '$h');
  });

  test('real words stay as written', () {
    final changed = [
      for (final w in keep)
        if (p.suggest('the $w here').any((x) => x.original == w && x.kind == PolishKind.spelling)) w,
    ];
    expect(changed.length, lessThanOrEqualTo(1), reason: '$changed');
  });
}
